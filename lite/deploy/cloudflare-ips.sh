#!/usr/bin/env bash
# Fetches published Cloudflare IPv4 and IPv6 ranges, generates a Caddy snippet for trusted proxies,
# and restricts UFW ports 80 and 443 so only Cloudflare proxy traffic can reach the origin.
#
# Idempotent: safe to run repeatedly or via systemd timer. SSH (port 22) is never touched.
set -euo pipefail

TAG="cloudflare-ip"
CADDY_SNIPPET_FILE="${CADDY_SNIPPET_FILE:-/etc/caddy/cloudflare-ips.caddy}"
IPV4_URL="https://www.cloudflare.com/ips-v4"
IPV6_URL="https://www.cloudflare.com/ips-v6"

if [[ $EUID -ne 0 ]]; then
  echo "run as root" >&2
  exit 1
fi

remove_ufw_rules() {
  if command -v ufw >/dev/null 2>&1; then
    echo "Removing UFW rules with comment '$TAG'..."
    while true; do
      local num
      num="$(ufw status numbered 2>/dev/null | grep -E "# ${TAG}" | tail -n 1 | sed -E 's/^\[ *([0-9]+)\].*/\1/' || true)"
      if [[ -n "$num" && "$num" =~ ^[0-9]+$ ]]; then
        echo "y" | ufw delete "$num" >/dev/null 2>&1 || break
      else
        break
      fi
    done
    echo "UFW rules tagged '$TAG' removed."
  fi
}

if [[ "${1:-}" == "--remove" ]]; then
  remove_ufw_rules
  if [[ -f "$CADDY_SNIPPET_FILE" ]]; then
    rm -f "$CADDY_SNIPPET_FILE"
    echo "Removed $CADDY_SNIPPET_FILE"
  fi
  exit 0
fi

echo "Fetching Cloudflare IP ranges..."
ipv4_list="$(curl -sSfL --connect-timeout 10 --max-time 30 "$IPV4_URL")"
ipv6_list="$(curl -sSfL --connect-timeout 10 --max-time 30 "$IPV6_URL")"

if [[ -z "$ipv4_list" || -z "$ipv6_list" ]]; then
  echo "Failed to fetch Cloudflare IP ranges or empty response received." >&2
  exit 1
fi

# Validate that returned lines match IP CIDR formats
combined_ips="$(printf "%s\n%s" "$ipv4_list" "$ipv6_list" | grep -E '^[0-9a-fA-F:./]+$')"
if [[ -z "$combined_ips" ]]; then
  echo "Fetched IP list did not contain valid CIDR blocks." >&2
  exit 1
fi

# 1. Generate Caddy trusted proxies snippet
mkdir -p "$(dirname "$CADDY_SNIPPET_FILE")"
tmp_caddy="$(mktemp)"
space_separated_ips="$(echo "$combined_ips" | tr '\n' ' ' | sed 's/ $//')"

cat <<EOF > "$tmp_caddy"
# Generated by cloudflare-ips.sh on $(date -u +"%Y-%m-%d %H:%M:%SZ") - DO NOT EDIT MANUALLY
servers {
    trusted_proxies static ${space_separated_ips}
    client_ip_headers CF-Connecting-IP
}
EOF

mv "$tmp_caddy" "$CADDY_SNIPPET_FILE"
chmod 644 "$CADDY_SNIPPET_FILE"
echo "Updated Caddy snippet at $CADDY_SNIPPET_FILE"

if command -v systemctl >/dev/null 2>&1 && systemctl is-active --quiet caddy 2>/dev/null; then
  echo "Reloading Caddy configuration..."
  systemctl reload caddy 2>/dev/null || caddy reload --config /etc/caddy/Caddyfile 2>/dev/null || true
fi

# 2. Lock down UFW ports 80/443 to Cloudflare IPs
if command -v ufw >/dev/null 2>&1; then
  echo "Configuring UFW rules for Cloudflare origin lock..."
  # Remove general/unrestricted allow rules for 80 and 443
  ufw delete allow 80/tcp >/dev/null 2>&1 || true
  ufw delete allow 443/tcp >/dev/null 2>&1 || true
  ufw delete allow 80 >/dev/null 2>&1 || true
  ufw delete allow 443 >/dev/null 2>&1 || true
  ufw delete allow 'Nginx Full' >/dev/null 2>&1 || true
  ufw delete allow 'Nginx HTTP' >/dev/null 2>&1 || true
  ufw delete allow 'Nginx HTTPS' >/dev/null 2>&1 || true

  # Add each Cloudflare range (UFW automatically skips existing identical rules)
  while IFS= read -r ip; do
    [[ -z "$ip" ]] && continue
    ufw allow proto tcp from "$ip" to any port 80 comment "$TAG" >/dev/null 2>&1
    ufw allow proto tcp from "$ip" to any port 443 comment "$TAG" >/dev/null 2>&1
  done <<< "$combined_ips"

  echo "UFW rules successfully updated. Ports 80 and 443 restricted to Cloudflare proxies."
else
  echo "UFW not found; skipped firewall configuration."
fi
